export function rootHelp(): string {
  return `${ROOT}\n`;
}

export function commandHelp(command: string, sub?: string): string {
  const key = sub === undefined ? command : `${command} ${sub}`;
  const text = COMMANDS[key] ?? COMMANDS[command];
  if (text === undefined) {
    return `${ROOT}\n`;
  }
  return `${text}\n`;
}
