export async function seedDemoRegistry(options: {
  registryPath: string;
  keysDir: string;
  now?: Date;
  forceKeys?: boolean;
}): Promise<string[]> {
  const now = options.now ?? new Date();
  await mkdir(options.keysDir, { recursive: true });
  await writeFile(
    join(options.keysDir, "README.txt"),
    [
      "Demo Ed25519 keys generated by ans-kit.",
      "They are disposable local fixtures for the sample agents.",
      "Do not use them outside this machine, and do not commit them.",
      "",
    ].join("\n"),
    "utf8",
  );
  const registry = await LocalRegistry.create(options.registryPath, now);
  const names: string[] = [];
  for (const [index, spec] of DEMO_SPECS.entries()) {
    const pair = generateKeyPair();
    const { keyName, ...input } = spec;
    await writeKeyPairFiles(join(options.keysDir, keyName), pair, options.forceKeys ?? false);
    const registeredAt = new Date(now.getTime() + index * 1000);
    const signed = signRegistration({ ...input, registeredAt }, pair.privateKeyPem, { now });
    await registry.register(signed);
    names.push(signed.document.ansName);
  }
  return names;
}
